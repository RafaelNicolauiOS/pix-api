-- Razão (livro contábil): cada mudança de saldo vira um lançamento imutável.
-- Invariante conferida pelo batch noturno em COBOL: soma do razão de uma conta = saldo da conta.
--
-- Sem chave estrangeira para conta: quando uma conta é encerrada, a linha em "conta" some,
-- mas o histórico contábil precisa continuar existindo.

CREATE TABLE lancamento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id         BIGINT                   NOT NULL,
    tipo             VARCHAR(12)              NOT NULL, -- ABERTURA, PIX_ENVIADO, PIX_RECEBIDO, ENCERRAMENTO
    valor            NUMERIC(15, 2)           NOT NULL, -- sempre positivo; o tipo define crédito ou débito
    realizado_em     TIMESTAMP WITH TIME ZONE NOT NULL,
    transferencia_id UUID                               -- mesmo id do TransferenciaRealizadaEvent
);

CREATE INDEX idx_lancamento_conta ON lancamento (conta_id);
CREATE INDEX idx_lancamento_realizado_em ON lancamento (realizado_em);

-- Implantação: contas que já existem (ex.: produção no Render) ganham um lançamento de abertura
-- com o saldo atual, para o razão começar fechado com os saldos.
INSERT INTO lancamento (conta_id, tipo, valor, realizado_em)
SELECT id, 'ABERTURA', saldo, CURRENT_TIMESTAMP
FROM conta;
